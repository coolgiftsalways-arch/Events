// Booking as the vendor / organiser pages expect it
module.exports = function bookingView(b) {
  return {
    id: String(b._id),
    _id: String(b._id),
    kind: b.kind,
    eventId: String(b.event?._id || b.event),
    eventTitle: b.eventTitle,
    eventName: b.eventTitle,
    eventDate: b.eventDate,
    eventLocation: b.eventVenue,
    venue: b.eventVenue,
    vendorName: b.vendorName,
    name: b.vendorName,
    businessName: b.businessName,
    email: b.email,
    phone: b.phone,
    category: b.category,
    products: b.products,
    description: b.products,
    stall: b.stall,
    stallType: b.stall?.type || "",
    stallSize: b.stall?.size || "",
    originalPrice: b.originalPrice,
    discount: b.discountPercent || b.discount,
    discountAmount: b.discount,
    finalPrice: b.total,
    amount: b.total,
    total: b.total,
    bookingFee: b.bookingFee,
    paymentOption: b.paymentOption,
    amountToPayNow: b.amountToPayNow,
    amountPaid: b.amountPaid,
    remainingAmount: Math.max(0, b.total - b.amountPaid),
    membershipName: b.membershipName,
    status: b.status,
    paymentStatus: b.paymentStatus,
    paymentUrl: b.paymentStatus === "awaiting" ? b.paymentUrl : undefined,
    note: b.note,
    appliedAt: b.createdAt,
    createdAt: b.createdAt,
    paidAt: b.paidAt,
  };
};
